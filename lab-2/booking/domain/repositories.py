"""Порты репозиториев (Protocol) для бронирования."""

from typing import Protocol

from .aggregates import Booking, Employee, Room
from .value_objects import BookingId, EmployeeId, RoomId


class RoomRepository(Protocol):
    def get(self, room_id: RoomId) -> Room: ...
    def save(self, room: Room) -> None: ...


class EmployeeRepository(Protocol):
    def get(self, employee_id: EmployeeId) -> Employee: ...
    def save(self, employee: Employee) -> None: ...


class BookingRepository(Protocol):
    def next_id(self) -> BookingId: ...
    def get(self, booking_id: BookingId) -> Booking: ...
    def save(self, booking: Booking) -> None: ...

    # Нужен для инварианта 2 (брони одной комнаты не пересекаются)
    def list_by_room(self, room_id: RoomId) -> list[Booking]: ...
